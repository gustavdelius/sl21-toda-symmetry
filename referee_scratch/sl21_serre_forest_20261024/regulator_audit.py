"""Checks of the analytic regulator and the potentially evanescent anomaly."""
import sympy as S
import numpy as np

passed=failed=0
def check(name,ok,detail=''):
    global passed,failed
    passed+=int(bool(ok));failed+=int(not bool(ok))
    print(('PASS ' if ok else 'FAIL ')+name+(': '+detail if detail else ''),flush=True)
def eq(name,a,b=0):check(name,S.expand(S.together(a-b).as_numer_denom()[0])==0)

g,rho=S.symbols('g rho',nonzero=True);t=2/rho
eq('pair subtraction retains independent exponent',2*(t-2)/(g-1)+2*t,2*t*(g-rho)/(g-1))
for nA,nB,target in [(0,2,g-1),(0,3,3*g-2),(1,1,2-rho),(1,2,1+g-2*rho),
                    (1,3,3*(g-rho)),(2,1,4+g-2*rho),(3,1,6+3*(g-rho))]:
    vertex=g*(S.binomial(nA,2)+S.binomial(nB,2))-rho*nA*nB+nA-nB
    derivative=-nB
    relative_measure=nA+nB+1
    eq(f'raw source collision count A={nA}, B={nB}',vertex+derivative+relative_measure,target)

# A simple pole would invalidate diagonal specialization of a vanishing
# shuffle coefficient. This diagnostic is deliberately NOT the actual kernel.
s,u=S.symbols('s u',nonzero=True)
D=(s-1)*(s+1)*(s-u)*(s*s-u)*(u+1)/s**4
derivative=S.diff(D,u).subs(u,s)*(-S.I*S.pi*s)
eq('hypothetical simple-pole anomaly is nonzero',derivative/3,S.I*S.pi*(s-1/s)**2/3)
rr=-np.sqrt(2)/5;ss=np.exp(-1j*np.pi*rr)
pred=1j*np.pi*(ss-1/ss)**2/3
errors=[]
for delta in (.01,.005,.0025):
    uu=np.exp(-1j*np.pi*(rr+delta))
    dd=(ss-1)*(ss+1)*(ss-uu)*(ss*ss-uu)*(uu+1)/ss**4
    errors.append(abs(dd/(3*delta)-pred))
check('hypothetical pole times zero approaches a finite nonzero value',errors[-1]<errors[0]/3 and abs(pred)>1)

# Exact angular quadrature for a nonconstant smooth field at an isolated
# Cauchy double pole. Only its holomorphic quadratic coefficient contributes
# at order epsilon^2; no epsilon^0 normalization is generated by the disk.
angles=2*np.pi*(np.arange(512)+.5)/512
unit=np.exp(1j*angles)
for eps in (.08,.04,.02):
    # Midpoint radial integration is exact for the surviving term r dr.
    rad=eps*(np.arange(128)+.5)/128
    v=rad[:,None]*unit[None,:]
    field=1+.2*v+.31*np.conj(v)+(.43+.17j)*v*v+.29*v*np.conj(v)+.13*np.conj(v)**2
    val=2*np.pi*(eps/128)*np.sum(rad*np.mean(field/(v*v),axis=1))
    expected=np.pi*(.43+.17j)*eps*eps
    check(f'isolated double-pole disk has only positive power, eps={eps}',abs(val-expected)<2e-13)

# Complete the leading real-axis source moment audit with generic positions.
# For polynomial total degree below 2N-2, the area moment is the sum of
# double-pole coefficients; this includes the divergent jets used in the forest.
w=S.symbols('w');x=S.symbols('x',nonzero=True)
for N,pos in [(2,[S.Integer(0),x]),(3,[S.Integer(0),S.Integer(1),x])]:
    for m in range(N):
        for n in range(N-m):
            actual=0;expected=0
            for i,zi in enumerate(pos):
                H=w**m/S.prod((w-zj)**2 for j,zj in enumerate(pos) if j!=i)
                actual-=zi**(n+1)*S.diff(H,w).subs(w,zi)/S.Integer(n+1)
                expected+=zi**(m+n)/S.prod((zi-zj)**2 for j,zj in enumerate(pos) if j!=i)
            eq(f'generic-position area moment N={N}, m={m}, n={n}',actual,expected)
print(f'RESULT {passed} PASS, {failed} FAIL',flush=True)
raise SystemExit(bool(failed))
