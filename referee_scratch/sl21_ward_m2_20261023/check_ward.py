"""Independent Wick/point-splitting checks for the order-mass-squared Ward test.

No previous referee or book check script is imported. See the new report for
the regulator, cocycle convention, and the precise scope of the conclusion.
Run: python3 -u referee_scratch/sl21_ward_m2_20261023/check_ward.py
"""
import math
import numpy as np
import sympy as s


def check(name, result):
    if isinstance(result, s.MatrixBase):
        ok = all(s.simplify(v) == 0 for v in result)
    elif isinstance(result, bool):
        ok = result
    else:
        ok = s.simplify(result) == 0
    print(('PASS' if ok else 'FAIL') + ' ' + name, flush=True)
    assert ok, name


b = s.symbols('b', nonzero=True)
t = b**2
I, rt = s.I, s.sqrt(2)
alpha = [s.Matrix([-1/rt, I/rt]), s.Matrix([rt, 0]),
         s.Matrix([-1/rt, -I/rt])]
check('root Gram matrix from component roots',
      s.Matrix(3, 3, lambda i,j: alpha[i].dot(alpha[j]))
      - s.Matrix([[0,-1,1],[-1,2,-1],[1,-1,0]]))
check('affine root sum', sum(alpha, s.zeros(2,1)))

# Reconstruct precisely the component action used, from Evans--Madsen (3.4).
u,v,mu0,mu2 = s.symbols('u v mu0 mu2')
phi = s.Matrix([u,v])
M = sum((mu * a * a.T * s.exp(a.dot(phi))
         for a,mu in [(alpha[0],mu0),(alpha[2],mu2)]), s.zeros(2,2))
check('odd-root pair potential coefficient',
      s.Rational(1,2)*sum(mi*mj*ai.dot(aj)*s.exp((ai+aj).dot(phi))
          for ai,mi in [(alpha[0],mu0),(alpha[2],mu2)]
          for aj,mj in [(alpha[0],mu0),(alpha[2],mu2)])
      - mu0*mu2*s.exp(-rt*u))
mu = s.symbols('mu')
check('source Yukawa Hessian matrix at equal masses',
      M.subs({mu0:mu,mu2:mu})
      - mu*s.exp(-u/rt)*s.Matrix([[s.cos(v/rt),s.sin(v/rt)],
                                [s.sin(v/rt),-s.cos(v/rt)]]).applyfunc(lambda q:q.rewrite(s.exp)))

# Exterior product: a check of :chi_0 chi_2: = i :psi^u psi^v:.
check('fermion bilinear bosonization sign',
      s.det(s.Matrix.hstack(alpha[0],alpha[2]))-I)
check('mixed full Yukawa OPE sign: i^2 times one Wick crossing', I**2*(-1)-1)

p = [-I*b*a for a in alpha]
a0 = p[0].col_join(s.Matrix([I]))
a2 = p[2].col_join(s.Matrix([-I]))
T = s.simplify(a0+a2)
a1 = p[1].col_join(s.Matrix([0]))
d = s.simplify(2*T/T.dot(T))
C = a0
D = s.simplify(a0-a2)
k = s.simplify(d+T)
check('bosonized self products', s.Matrix([a0.dot(a0)+1,a2.dot(a2)+1]))
check('bosonized mutual product', a0.dot(a2)-(1-t))
check('pair momentum squared', T.dot(T)+2*t)
check('pair dual momentum', d-s.Matrix([-I*rt/b,0,0]))
check('T=-b^2 d and a1=-T', (T+t*d).col_join(a1+T))
check('dual-current pair contractions', s.Matrix([d.dot(a0)-1,d.dot(a2)-1]))
free = s.Matrix([0,rt,I*b])
check('free direction orthogonal to all perturbing momenta',
      s.Matrix([free.dot(a0),free.dot(a1),free.dot(a2)]))
check('free direction norm', free.dot(free)-(2-t))

# Two independent OPE orientations, generated by the Wick exponential.
r = s.symbols('r')
x = s.Matrix(s.symbols('x0:3'))       # dX
y = s.Matrix(s.symbols('y0:3'))       # d^2 X
z = s.Matrix(s.symbols('z0:3'))       # d^3 X

def taylor(momentum):
    # The degree-two Taylor polynomial of exp(p.[X(w+r)-X(w)]).
    px = momentum.dot(x)
    return 1+r*px+r*r*(momentum.dot(y)+px*px)/2

def res_perturbation(a):
    pole = s.simplify(d.dot(a))
    expr = s.expand(r**(-pole)*(C.dot(x)+C.dot(a)/r)*taylor(a))
    return s.expand(expr).coeff(r,-1)

def res_charge(a):
    pole = s.simplify(d.dot(a))
    expr = s.expand(r**(-pole)*(C.dot(x)+r*C.dot(y)
                        + r*r*C.dot(z)/2-C.dot(a)/r)*taylor(d))
    return s.expand(expr).coeff(r,-1)

check('fixed-current Yukawa 0 residue vanishes', res_perturbation(a0))
check('fixed-current Yukawa 2 residue is -b^2 derivative',
      res_perturbation(a2)+t*(d+a2).dot(x))
check('charge acts on Yukawa 0 by +derivative', res_charge(a0)-(d+a0).dot(x))
check('charge acts on Yukawa 2 by -derivative', res_charge(a2)+(d+a2).dot(x))
check('Jminus with even perturbation has no residue', res_perturbation(a1))
plus_res = s.expand(r**(-s.simplify((-d).dot(a1)))*taylor(a1)).coeff(r,-1)
check('Jplus even-vertex derivative coefficient',
      plus_res+t/(1-t)*(-d+a1).dot(x))
check('Jplus regular with both Yukawas and composite',
      all(s.simplify((-d).dot(a)) < 0 for a in [a0,a2,T]))

RP = res_perturbation(T)
RQ = res_charge(T)
A = T.dot(x)*D.dot(x)/2

def derivative_linear(vec):
    return vec.dot(y)+vec.dot(x)*k.dot(x)

check('composite fixed-current residue from Wick expansion',
      RP-(C.dot(x)*T.dot(x)-t*(T.dot(y)+T.dot(x)**2)/2))
check('composite nonderivative representative A',
      RP-derivative_linear(-t*T/2)-A)
check('charge residue has opposite nonderivative representative',
      RQ-derivative_linear(D/2)+A)

# General level-one improvement is fixed by coefficients of d^2 X.
required = s.Matrix([s.diff(RP,yi) for yi in y])
check('unique level-one primitive forced by second derivatives', required+t*T/2)
check('composite remainder is not identically zero', s.expand(A) != 0)

# Generate the contact boundary polynomial by expanding both collision ends.
# F0+F2 = r^(t-2) rbar^(t-1) (E0-E2), including the minus sign
# from the current's contraction with the other insertion.
end0 = taylor(d+a0)
end2 = taylor(a0)
B = s.expand(end0-end2).coeff(r,2)
check('boundary polynomial from two-end Taylor expansion',
      B-(d.dot(y)/2+d.dot(x)**2/2+C.dot(x)*d.dot(x)))
check('boundary cohomology is -A/b^2', B-derivative_linear(d/2)+A/t)
check('exact charge/contact descent identity', RQ-t*B-derivative_linear(C))
check('exact fixed-current/contact descent identity',
      RP+t*B-derivative_linear(t*(t+1)*d/2))
check('change of OPE orientation is a total derivative',
      RP+RQ-derivative_linear(C+t*(t+1)*d/2))

# Check both endpoints directly in the three-operator Wick product.
# Common factors r^(-(1-t))*rbar^(-(1-t))*E_i are suppressed.
sep, small = s.symbols('sep small', nonzero=True)
# z=w0+small: current exponent contributes 1+small*(d.dX)+... .
near0 = ((1/sep-small/sep**2)/small
         * (C.dot(x)+1/small-(1-t)*(1/sep-small/sep**2))
         * (1+small*d.dot(x)))
# z=w2+small, so z-w0=small-sep.
near2 = ((-1/sep-small/sep**2)/small
         * (C.dot(x)-1/sep-small/sep**2-(1-t)/small)
         * (1+small*d.dot(x)))
check('full three-point Wick product: first collision endpoint',
      s.expand(near0).coeff(small,-1)
      -((d+a0).dot(x)/sep-(2-t)/sep**2))
check('full three-point Wick product: second collision endpoint',
      s.expand(near2).coeff(small,-1)
      -((d+a2).dot(x)/sep+(2-t)/sep**2))

# Field normalization and the action coefficient, derived in the report.
g = s.symbols('g', nonzero=True)
check('canonical boson kinetic coefficient', 2/g**2*(g/(2*s.sqrt(s.pi)))**2-1/(2*s.pi))
check('canonical holomorphic fermion kinetic coefficient',
      -I/g**2*(s.exp(I*s.pi/4)*g/s.sqrt(2*s.pi))**2-1/(2*s.pi))
check('canonical antiholomorphic fermion kinetic coefficient',
      I/g**2*(s.exp(-I*s.pi/4)*g/s.sqrt(2*s.pi))**2-1/(2*s.pi))
check('source exponent matches -i b Phi', (-I*b).subs(b,I*g/(2*s.sqrt(s.pi)))-g/(2*s.sqrt(s.pi)))
check('source composite matches Ward counterterm coefficient',
      (-mu0*mu2/(4*t)).subs(b,I*g/(2*s.sqrt(s.pi)))-s.pi*mu0*mu2/g**2)
ell = s.symbols('ell', positive=True)
check('bare composite normal-ordering exponent', T.dot(T)/2*(-2*s.log(ell))-2*t*s.log(ell))
check('individual bosonic Yukawa exponent has no self-normalization', p[0].dot(p[0])+p[2].dot(p[2]))

rho,tau = s.symbols('rho tau', positive=True)
check('radial primitive gives pi*epsilon^(2t)/t',
      s.diff(s.pi*rho**(2*tau)/tau,rho)-2*s.pi*rho**(2*tau-1))
lprod,epow,kapR = s.symbols('lambda_product epsilon_power kappa_R')
kap = kapR-lprod*epow/t
check('combined Ward coefficient leaves kappa_R only', kap+lprod*epow/t-kapR)
check('full descent at zero finite composite coupling',
      (-lprod*epow/t)*RQ+lprod*epow*B
      -derivative_linear((-lprod*epow/t)*C))
check('same-Yukawa collisions are nonsingular', a0.dot(a0)+1)

print('FORMULAS: t=b^2; A=(T.dX)(D.dX)/2; [B]=-[A]/t', flush=True)
print('FORMULAS: kappa(eps)=kappa_R-lambda0*lambda2*eps^(2t)/t', flush=True)
print('FORMULAS: b=i*g/sqrt(4*pi), lambda_j=mu_j/2', flush=True)

# Numerically integrate the actual collision circle, not just its coefficient.
# Include antiholomorphic jets to check suppression of further descendants.
def circle_test(tval):
    bval = complex(tval)**0.5
    sub = {b:bval}
    dv = np.array(d.subs(sub), dtype=complex).reshape(3)
    av = np.array(a0.subs(sub), dtype=complex).reshape(3)
    xv = np.array([0.31+0.17j, -0.22+0.11j, 0.19-0.13j])
    yv = np.array([-0.08+0.16j, 0.12-0.03j, 0.07+0.04j])
    xb = np.array([0.15-0.04j, 0.06+0.02j, -0.05+0.09j])
    yb = np.array([0.03+0.01j, -0.02+0.03j, 0.01-0.01j])
    Bv = dv.dot(yv)/2+dv.dot(xv)**2/2+av.dot(xv)*dv.dot(xv)
    angles = 2*np.pi*np.arange(8192)/8192
    errors = []
    for eps in [0.10,0.05,0.025,0.0125]:
        rr = eps*np.exp(1j*angles)
        rb = rr.conjugate()
        common = np.exp(rr*av.dot(xv)+rr**2*av.dot(yv)/2
                        +rb*av.dot(xb)+rb**2*av.dot(yb)/2)
        difference = common*np.expm1(rr*dv.dot(xv)+rr**2*dv.dot(yv)/2)
        # -epsilon/2 integral e^-i theta * r^(t-2) rbar^(t-1).
        boundary = -np.pi*eps**(2*tval-2)*np.mean(np.exp(-2j*angles)*difference)
        expected = -np.pi*eps**(2*tval)*Bv
        error = abs((boundary-expected)/expected)
        errors.append(error)
        print(f'NUMERICAL t={tval:.15g} eps={eps:.3g} relative_error={error:.6g}', flush=True)
    check(f'circle integral coefficient and O(eps^2) remainder at t={tval:.15g}',
          errors[-1] < 2e-5 and all(3.8 < errors[i]/errors[i+1] < 4.2 for i in range(len(errors)-1)))


circle_test(math.sqrt(2)/3)
circle_test(-math.sqrt(2)/3)
