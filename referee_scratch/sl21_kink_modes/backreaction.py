"""Full two-generator Grassmann check of a dressed Toda kink and its charges.

The body of u is i*chi/sqrt(2), v has a degree-two nilpotent correction.
No author/book check scripts are imported.
"""
from kink_modes import y,mu,rt,roots,dx,clean,mode_data
import sympy as s

class G:
    def __init__(self,terms=0):
        self.d=terms if isinstance(terms,dict) else {0:s.sympify(terms)}
        self.d={k:s.factor(v) for k,v in self.d.items() if v!=0}
    def __add__(self,other):
        other=other if isinstance(other,G) else G(other)
        return G({k:self.d.get(k,0)+other.d.get(k,0) for k in self.d.keys()|other.d.keys()})
    __radd__=__add__
    def __neg__(self):return G({k:-v for k,v in self.d.items()})
    def __sub__(self,other):return self+-other if isinstance(other,G) else self+G(-other)
    def __rsub__(self,other):return G(other)+-self
    def __mul__(self,other):
        other=other if isinstance(other,G) else G(other)
        out={}
        for a,u in self.d.items():
            for b,v in other.d.items():
                if a&b:continue
                inversions=sum(1 for i in range(2) for j in range(2) if i>j and (a>>i)&1 and (b>>j)&1)
                out[a|b]=out.get(a|b,0)+(-1)**inversions*u*v
        return G(out)
    __rmul__=__mul__
    def derivative(self):return G({k:dx(v) for k,v in self.d.items()})
    def zero(self):return all(s.factor(v)==0 for v in self.d.values())
    def __repr__(self):return str(self.d)

def dot(a,b):return sum((u*v for u,v in zip(a,b)),G(0))

def main():
    aa,bb=G({1:s.S.One}),G({2:s.S.One});ab=aa*bb
    assert (aa*aa).zero() and (bb*bb).zero() and (aa*bb+bb*aa).zero()
    print('PASS independent Grassmann algebra: a^2=b^2=0, ab=-ba')
    for orientation in (1,-1):
        chi,w,f,r,M,U=mode_data(orientation)
        v2=s.I*y/(2*rt*mu*(1+orientation*s.I*y))
        plus=[aa*f,bb*f];minus=[aa*(orientation*f),bb*(-orientation*f)]
        exps=[]
        for j in range(3):
            body=w**-2 if j==1 else w
            exps.append(G(body)*(1+ab*(roots[j][1]*v2)))
        mass=[[sum((exps[j]*(mu*roots[j][a]*roots[j][b]) for j in (0,2)),G())
               for b in range(2)] for a in range(2)]
        # Static fermion equations in the full corrected field.
        for a in range(2):
            assert (plus[a].derivative()-dot(mass[a],minus)).zero()
            assert (minus[a].derivative()-dot(mass[a],plus)).zero()
        params=[mu,mu**2,mu]
        gradient=[exps[1]*(mu**2*roots[1][a]) for a in range(2)]
        for a in range(2):
            for j in (0,2):
                for k in (0,2):
                    gradient[a]+=exps[j]*exps[k]*(s.Rational(1,2)*mu**2*(roots[j]+roots[k])[a]*(roots[j].T*roots[k])[0])
        yuk=[]
        for a in range(2):
            yuk.append(sum((exps[j]*dot(list(roots[j]),plus)*dot(list(roots[j]),minus)*(mu*roots[j][a]) for j in (0,2)),G()))
        bos_second=[G(s.I*dx(dx(chi))/rt),ab*dx(dx(v2))]
        for a in range(2):assert (bos_second[a]-gradient[a]+yuk[a]*s.I).zero()
        print('PASS exact full boson and fermion EOM through all Grassmann degrees, orientation',orientation)
        delta=s.simplify(s.limit(v2,y,s.oo)-s.limit(v2,y,0))
        assert delta==orientation/(2*rt*mu)
        assert s.simplify(dx(v2)-s.I*f**2/rt)==0
        print('PASS nilpotent massless-field backreaction: v2(+inf)-v2(-inf)=',delta)
        # Source normalization: action has an overall 1/g^2; this charge is
        # generated by psi+ -> R psi+, psi- -> R^-1 psi-.
        g=s.symbols('g',positive=True)
        rhoF=(-s.I*plus[0]*plus[1]+s.I*minus[0]*minus[1])*(1/g**2)
        assert (ab*dx(v2)+rhoF*(g**2/(2*rt))).zero()
        IB=-orientation*s.I/(2*mu)
        QFcoeff=-2*s.I*IB/g**2
        assert s.simplify(delta+g**2*QFcoeff/(2*rt))==0
        print('PASS static charge/boundary relation Delta v = -g^2 Q_F/(2*sqrt(2))')
    # Full local axial Noether identity with arbitrary symmetric traceless M.
    c,d=s.symbols('c d',real=True)
    P=[G({1:s.S.One}),G({2:s.S.One})]
    # Use a separate four-generator exterior algebra for the current identity
    # in charges.py; here verify the coefficient matrix conditions.
    J=s.Matrix([[0,-1],[1,0]]);M=s.Matrix([[c,d],[d,-c]])
    assert M*J+J*M==s.zeros(2)
    assert (J*M).T==J*M
    print('PASS full axial symmetry coefficient identity M J+J M=0')
    print('Fixed identical v vacua at both infinities require ab=0 for this exact static family.')
    print('Allowing the nilpotent boundary shift gives an exact finite-energy supernumber solution.')

if __name__=='__main__':main()
